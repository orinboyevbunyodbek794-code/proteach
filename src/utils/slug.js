/**
 * Kurs nomidan URL uchun slug yasash (lotin, kirill harflari transliteratsiyasi bilan).
 */
'use strict';

const CYR = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'j', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'x', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'sh', ъ: '', ы: 'i', ь: '', э: 'e', ю: 'yu', я: 'ya',
  ў: 'o', қ: 'q', ғ: 'g', ҳ: 'h',
};

function slugify(input) {
  return String(input || '')
    .toLowerCase()
    .replace(/[ʻʼ‘’'`ʻʼ]/g, '') // o'zbekcha tutuq belgilari
    .split('')
    .map((ch) => (CYR[ch] !== undefined ? CYR[ch] : ch))
    .join('')
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80)
    .replace(/-+$/g, '');
}

module.exports = { slugify };
